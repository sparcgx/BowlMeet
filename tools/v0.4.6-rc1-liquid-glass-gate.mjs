import fs from 'node:fs';
const read=p=>fs.readFileSync(p,'utf8');
const h=read('index.html'), c=read('assets/liquid-glass-dev4.css'), m=read('manifest.webmanifest'), w=read('sw.js');
const tests=[]; const t=(name,ok)=>tests.push({name,ok:!!ok});
t('APP_VERSION RC.1',h.includes("const APP_VERSION='0.4.6-RC.1'"));
t('Title RC.1',h.includes('BowlMeet v0.4.6-RC.1'));
t('Glass CSS linked',h.includes('assets/liquid-glass-dev4.css'));
t('Mobile Glass Dock',h.includes('class="mobile-glass-dock"'));
t('Mobile More Sheet',h.includes('id="mobileMoreSheet"'));
t('10-frame normalization',h.includes('function normalizeBowlingRoll')&&h.includes('function normalizeBowlingFrame'));
t('Current meetup context',h.includes("renderLeaderboard(currentMeetupId||'all')")&&h.includes("renderShare(currentMeetupId||'')"));
t('PUBLIC-only anchor',h.includes("const PUBLIC_HISTORY_CODE='PUBLIC'"));
t('Backup export',h.includes('async function exportFullBackup'));
t('Snapshot restore',h.includes('async function restoreSnapshot'));
t('DB version unchanged',h.includes('const DB_VERSION=2'));
t('Reduced motion',h.includes('prefers-reduced-motion'));
t('Reduced transparency',h.includes('prefers-reduced-transparency')&&c.includes('prefers-reduced-transparency'));
t('Safe area',h.includes('safe-area-inset-bottom'));
t('Manifest RC.1',m.includes('v0.4.6-RC.1'));
t('SW RC cache',w.includes('bowlmeet-v0.4.6-rc1-shell'));
t('SW caches glass CSS',w.includes('./assets/liquid-glass-dev4.css'));
t('No SQL in glass CSS',!c.includes('CREATE TABLE')&&!c.includes('ALTER TABLE'));
t('No JS in glass CSS',!c.includes('<script')&&!c.includes('javascript:'));
const failed=tests.filter(x=>!x.ok);
console.log(JSON.stringify({total:tests.length,pass:tests.length-failed.length,fail:failed.length,failed},null,2));
if(failed.length) process.exit(1);
