check('Stable title',h.includes('BowlMeet v0.4.6</title>'));
check('No RC label',!h.includes('0.4.6-RC.1')&&!h.includes('Release Candidate'));
check('Stable label',h.includes('· Stable'));
check('Production PUBLIC code',h.includes("const PUBLIC_HISTORY_CODE='PUBLIC'"));
check('Production DB namespace',h.includes("const DB_NAME='bowlingMeetup.local'"));
check('Session namespace',h.includes("const V2KEY='bowlingScoreWorkstation.sessions.v2'"));
check('Active Meetup namespace',h.includes("const ACTIVEKEY='bowlingMeetup.activeEvent.v3'"));
check('Public control namespace',h.includes("const PUBLIC_CONTROL_KEY='bowlingMeetup.publicControl.v044'"));
check('DB version unchanged',h.includes('const DB_VERSION=2'));
check('Bowling normalization retained',h.includes('function normalizeBowlingRoll')&&h.includes('function normalizeBowlingFrame'));
